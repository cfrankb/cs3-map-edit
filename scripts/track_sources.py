#!/usr/bin/env python3
"""Inventory the map editor sources and track their git hashes in tests/TRACKER.md.

    scripts/track_sources.py           regenerate tests/TRACKER.md, keeping manual columns
    scripts/track_sources.py --check   exit non-zero if a source changed or is not tracked

See tests/TESTING.md: src/runtime/ is excluded (covered by another project).
"""

import argparse
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "src"
TRACKER = ROOT / "tests" / "TRACKER.md"
EXTENSIONS = {".h", ".hpp", ".cpp"}
EXCLUDED_DIR = "runtime"

# Tracked for completeness but not unit-testable.
NOT_TESTABLE = {
    "src/main.cpp": "process entry point, single-instance QLocalServer",
    "src/app_version.h": "build-generated version constants",
}

HEADER = """# Source tracker

Generated by `scripts/track_sources.py` (`git hash-object` per file) - do not edit hashes by hand.
`Test target` and `Status` are maintained by hand: `todo` | `partial` | `covered` | `n/a`.
"""

COLUMNS = ("Source", "Hash", "Test target", "Status", "Note")


def sources():
    """Source files under src/, relative to the repo root, excluding src/runtime/."""
    return sorted(
        path.relative_to(ROOT).as_posix()
        for path in SRC.rglob("*")
        if path.suffix in EXTENSIONS
        and path.is_file()
        and EXCLUDED_DIR not in path.relative_to(SRC).parts
    )


def git_hash(relative_path):
    return subprocess.run(
        ["git", "hash-object", relative_path],
        cwd=ROOT,
        check=True,
        capture_output=True,
        text=True,
    ).stdout.strip()


def read_tracker():
    """Existing rows, keyed by source path: {path: (hash, target, status, note)}."""
    rows = {}
    if not TRACKER.exists():
        return rows
    for line in TRACKER.read_text(encoding="utf-8").splitlines():
        if not line.startswith("| src/"):
            continue
        cells = [cell.strip() for cell in line.strip().strip("|").split("|")]
        cells += [""] * (len(COLUMNS) - len(cells))
        rows[cells[0]] = tuple(cells[1:5])
    return rows


def write_tracker(rows):
    lines = [HEADER, "| " + " | ".join(COLUMNS) + " |", "|" + " --- |" * len(COLUMNS)]
    for path in sources():
        digest, target, status, note = rows[path]
        lines.append(f"| {path} | {digest} | {target} | {status} | {note} |")
    TRACKER.write_text("\n".join(lines) + "\n", encoding="utf-8")


def regenerate():
    old = read_tracker()
    rows = {}
    for path in sources():
        digest = git_hash(path)
        _, target, status, note = old.get(path, ("", "-", "todo", ""))
        if path in NOT_TESTABLE:
            status, note = "n/a", NOT_TESTABLE[path]
        rows[path] = (digest, target, status, note)
    write_tracker(rows)
    print(f"{TRACKER.relative_to(ROOT)}: {len(rows)} sources tracked")
    stale = sorted(set(old) - set(rows))
    if stale:
        print("removed (file deleted or moved to runtime/): " + ", ".join(stale))


def check():
    recorded = read_tracker()
    problems = []
    for path in sources():
        digest = git_hash(path)
        if path not in recorded:
            problems.append(f"untracked: {path} (run scripts/track_sources.py)")
        elif recorded[path][0] != digest:
            problems.append(f"changed: {path} (tests may need updating)")
    for path in sorted(set(recorded) - set(sources())):
        problems.append(f"stale entry: {path} (no longer an inventoried source)")

    if problems:
        print("\n".join(problems), file=sys.stderr)
        print(f"tracker out of date: {len(problems)} problem(s)", file=sys.stderr)
        return 1
    print(f"tracker ok: {len(recorded)} sources")
    return 0


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="verify TRACKER.md is up to date")
    args = parser.parse_args()
    return check() if args.check else regenerate()


if __name__ == "__main__":
    sys.exit(main())
