// Runtime boss data loader
//
// Replaces the autogenerated static bossdata.h/bossdata.cpp.
// The data is no longer compiled in; it is read at runtime from
// bosses.ini plus the JSON hitbox files it references.
//
// Public API is identical to the static version so the rest of the
// game (boss.cpp, game.cpp) needs no changes:
//     getBossData(type)        -> const bossData_t *
//     getHitboxes(sheet, frame)-> const sprite_hitbox_t *
//
// To activate:
//   1. copy this file to src/bossdata.h   (replaces the autogenerated one)
//   2. add bossdata_runtime.cpp to the build
//   3. call loadBossData(iniDir, hitboxDir) once at startup
//      (before any getBossData / getHitboxes call)

#pragma once

#include <cstdint>
#include <string>

#include "color.h"

// --- constants (previously #defines in the autogenerated header) ---
// Neutralize the legacy #define SHEET_SPACER from the autogenerated
// src/bossdata.h so it can't collide with this constexpr, no matter
// which header is included first.
constexpr int MAX_HITBOX_PER_FRAME = 4;

#define BOSS_MR_DEMON 0xb0
#define BOSS_GHOST 0xb1
#define BOSS_HARPY 0xb2
#define BOSS_BEHOLDER 0xb3
#define BOSS_COUNT 4

#define FLAG_FIREBALL 0x00000001
#define BOSS_FLAG_PROXIMITY_ATTACK 0x40000000
#define BOSS_FLAG_ICE_DAMAGE 0x80000000

namespace BossData
{
    constexpr int SHEET_SPACER = 1000;
    enum Path : uint8_t
    {
        NONE,
        ASTAR,
        BFS,
        LOS,
        ASTAR_SMOOTH
    };

    enum HitBoxType : uint8_t
    {
        MAIN,
        ATTACK,
        SPECIAL1,
        SPECIAL2
    };

    enum
    {
        NoTTL = -1
    };
}

struct boss_seq_t
{
    int base;
    int lenght;
};

struct hitbox_t
{
    int x;
    int y;
    int width;
    int height;
    int type;
};

struct sprite_hitbox_t
{
    int spriteID;
    int count;
    hitbox_t hitboxes[MAX_HITBOX_PER_FRAME];
};

struct bossData_t
{
    const char *name;     // boss name
    int speed;            // movement speed (lower = faster)
    int speed_anime;      // animation speed (lower = faster)
    int hp;               // hp
    uint8_t type;         // type
    int score;            // score received
    int damage;           // damage given (primary)
    int damage_attack;    // damage given (attack)
    int damage_special1;  // damage given (special1)
    int damage_special2;  // damage given (special2)
    uint32_t flags;       // custom flags
    uint32_t path;        // path finding algo
    uint8_t bullet;       // boss bullet
    uint8_t bullet_rate;  // boss bullet rate (lower = faster)
    uint8_t bullet_algo;  // bullet algo
    uint8_t bullet_sound; // bullet firing sound
    int bullet_ttl;       // bullet timeout (# of moves)
    uint8_t attack_sound; // sound during an attack
    int distance_chase;   // distance to engage chase
    int distance_pursuit; // continue pursuit within distance (chase)
    int distance_attack;  // distance within which the boss can attack
    bool is_goal;         // is this boss a map goal?
    bool show_details;    // display hp bar/name
    Color color_hp;       // hp bar color
    Color color_name;     // name color
    int aims;             // aim count (typically 1 or 4)
    boss_seq_t moving;    // animation seq: moving
    boss_seq_t attack;    // animation seq: attack
    boss_seq_t hurt;      // animation seq: hurt
    boss_seq_t death;     // animation seq: death
    boss_seq_t idle;      // animation seq: idle
    hitbox_t hitbox;      // primary hitbox
    int sheet;            // sprite sheet used
};

// --- runtime state (populated by loadBossData) ---
extern int g_bossCount;
extern int g_hitboxCount;
extern const bossData_t *g_bossData;
extern const sprite_hitbox_t *g_hitboxes;

// --- accessors (same signature as the static version) ---
inline const bossData_t *getBossData(const uint8_t type)
{
    for (int i = 0; i < g_bossCount; ++i)
    {
        if (g_bossData[i].type == type)
            return &g_bossData[i];
    }
    return nullptr;
}

inline const sprite_hitbox_t *getHitboxes(const int sheet, const int frameID)
{
    const int spriteID = sheet * BossData::SHEET_SPACER + frameID;
    for (int i = 0; i < g_hitboxCount; ++i)
    {
        if (g_hitboxes[i].spriteID == spriteID)
            return &g_hitboxes[i];
    }
    return nullptr;
}

// --- loader ---
// iniDir  : directory containing bosses.ini
// hitboxDir : directory containing the JSON hitbox files referenced by the ini
// Returns EXIT_SUCCESS (0) on success, EXIT_FAILURE (1) on error.
int loadBossData(const std::string &iniDir, const std::string &hitboxDir);

// Release memory held by the last loadBossData(). Safe to call repeatedly.
void freeBossData();
